"""
Contract between the MCP client (abi_core.abi_mcp.client) and the Semantic
Layer generated by the CLI: every argument the client sends must be declared
by the tool, because FastMCP rejects undeclared arguments.
Finding: .abi/specs/not-implemented/open-findings-2026-10-15.md (4.1).
"""

import ast
import asyncio
from pathlib import Path
from typing import Optional
from unittest.mock import AsyncMock, patch

import jinja2
import pytest
from fastmcp import Client, FastMCP

import abi_core.semantic.semantic_access_validator as sav
from abi_core.abi_mcp import client as abi_client

PACKAGES = Path(__file__).resolve().parents[1] / "packages"
SEMANTIC_LAYER_TEMPLATES = [
    PACKAGES / "abi-cli/src/abi_cli/scaffolding/service_semantic_layer/main.py.j2",
    PACKAGES / "abi-services/templates/service_semantic_layer/main.py.j2",
]


class _RecordingSession:
    """Stands in for ClientSession: records what call_tool is sent."""

    def __init__(self):
        self.calls = []

    async def call_tool(self, name, arguments):
        self.calls.append((name, arguments))


def _sent_arguments(exclude_ephemeral):
    session = _RecordingSession()
    asyncio.run(abi_client.find_agent(session, "q", {"headers": {}}, exclude_ephemeral))
    [(name, arguments)] = session.calls
    assert name == "find_agent"
    return set(arguments)


def _declared_parameters(template, tool_name):
    source = jinja2.Template(template.read_text()).render(project_name="p", domain="d")
    for node in ast.walk(ast.parse(source)):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == tool_name:
            args = node.args
            return {a.arg for a in args.posonlyargs + args.args + args.kwonlyargs}
    raise AssertionError(f"{tool_name} not found in {template}")


@pytest.mark.parametrize("template", SEMANTIC_LAYER_TEMPLATES, ids=lambda p: p.parts[-4])
@pytest.mark.parametrize("exclude_ephemeral", [False, True])
def test_template_find_agent_declares_every_argument_the_client_sends(template, exclude_ephemeral):
    missing = _sent_arguments(exclude_ephemeral) - _declared_parameters(template, "find_agent")
    assert not missing, f"client sends {sorted(missing)}, which {template.name} does not declare"


def test_fastmcp_rejects_an_argument_the_tool_does_not_declare():
    """Why the contract matters: the call fails before the tool runs, and the
    client only sees an error result (tool_find_agent turns it into None)."""
    mcp = FastMCP("contract")
    ran = []

    @mcp.tool(name="find_agent")
    @sav.validate_semantic_access
    async def find_agent(query: str, _request_context: dict = None) -> Optional[dict]:
        ran.append(query)
        return {"name": "agent"}

    async def call():
        allow = AsyncMock(return_value={"allowed": True, "reason": ""})
        with patch.object(sav._validator, "validate_access", allow):
            async with Client(mcp) as c:
                return await abi_client.find_agent(c.session, "q", {"headers": {}}, True)

    result = asyncio.run(call())
    assert result.isError
    assert "exclude_ephemeral" in result.content[0].text
    assert ran == []
